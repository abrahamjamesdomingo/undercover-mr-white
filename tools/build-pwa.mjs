// Build the installable copy of the game into docs/.
//
// iOS only installs web apps from an https:// page, so this build exists for the
// "add to home screen" route: publish docs/ once, open the URL on each phone, then
// it runs with the network off. The service worker precaches every asset, so the
// game boots from cache with no connection at all.
//
// docs/ is the folder GitHub Pages serves (Settings -> Pages -> main /docs), so
// https://<user>.github.io/<repo>/ is the installable app with no extra hosting.
//
//   node tools/build-pwa.mjs

import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { iconPng } from './make-icons.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Everything the browser asks for, relative to the site root. */
const ASSETS = [
  './',
  'index.html',
  'words.json',
  'manifest.webmanifest',
  'src/styles.css',
  'src/words.js',
  'src/game.js',
  'src/store.js',
  'src/app.js',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/apple-touch-icon.png',
];

const SOURCE_FILES = [
  'index.html',
  'words.json',
  'manifest.webmanifest',
  'src/styles.css',
  'src/words.js',
  'src/game.js',
  'src/store.js',
  'src/app.js',
];

const ICONS = [
  { file: 'icons/icon-192.png', size: 192 },
  { file: 'icons/icon-512.png', size: 512 },
  { file: 'icons/apple-touch-icon.png', size: 180 },
];

const HEAD = `  <link rel="manifest" href="manifest.webmanifest" />
  <link rel="apple-touch-icon" href="icons/apple-touch-icon.png" />
  <meta name="mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
  <meta name="apple-mobile-web-app-title" content="Undercover" />
`;

const REGISTER = `  <script>
    if ('serviceWorker' in navigator) {
      addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
    }
  </script>
`;

function manifest() {
  return {
    name: 'Undercover & Mr. White',
    short_name: 'Undercover',
    description: 'Pass-and-play Undercover & Mr. White party game',
    start_url: './',
    scope: './',
    display: 'standalone',
    orientation: 'portrait',
    background_color: '#0b0a10',
    theme_color: '#0c0b12',
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
    ],
  };
}

function serviceWorker(cache, assets) {
  return `// Generated by tools/build-pwa.mjs - do not edit.
const CACHE = ${JSON.stringify(cache)};
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

// Cache first: after the first visit the game never needs the network again.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy)).catch(() => {});
          return response;
        })
        .catch(() => caches.match('index.html'));
    }),
  );
});
`;
}

export async function buildPwa({ root = ROOT, out = path.join(ROOT, 'docs') } = {}) {
  const html = await readFile(path.join(root, 'index.html'), 'utf8');
  if (!html.includes('</head>') || !html.includes('</body>')) {
    throw new Error('index.html: expected head and body tags to inject into');
  }

  await rm(out, { recursive: true, force: true });
  await mkdir(path.join(out, 'src'), { recursive: true });
  await mkdir(path.join(out, 'icons'), { recursive: true });

  const pwaHtml = html.replace('</head>', `${HEAD}</head>`).replace('</body>', `${REGISTER}</body>`);
  await writeFile(path.join(out, 'index.html'), pwaHtml, 'utf8');

  for (const file of ['words.json', 'src/styles.css', 'src/words.js', 'src/game.js', 'src/store.js', 'src/app.js']) {
    await cp(path.join(root, file), path.join(out, file));
  }

  const manifestJson = `${JSON.stringify(manifest(), null, 2)}\n`;
  await writeFile(path.join(out, 'manifest.webmanifest'), manifestJson, 'utf8');

  for (const icon of ICONS) {
    await writeFile(path.join(out, icon.file), iconPng(icon.size));
  }

  // The cache name is a hash of the build, so any change retires the old cache.
  const hash = createHash('sha256');
  for (const file of SOURCE_FILES) {
    const content = await readFile(path.join(out, file));
    hash.update(file).update('\0').update(content);
  }
  const cache = `undercover-${hash.digest('hex').slice(0, 8)}`;

  await writeFile(path.join(out, 'sw.js'), serviceWorker(cache, ASSETS), 'utf8');

  // GitHub Pages runs Jekyll by default; this skips it so files are served as-is.
  await writeFile(path.join(out, '.nojekyll'), '', 'utf8');

  return { out, cache, assets: ASSETS.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  buildPwa()
    .then(({ out, cache, assets }) => {
      console.log(`pwa: ${path.relative(ROOT, out)}/ — ${assets} assets precached as ${cache}`);
    })
    .catch((error) => {
      console.error(`build failed: ${error.message}`);
      process.exitCode = 1;
    });
}
